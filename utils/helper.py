def is_hex(input_str: str):  # type: ignore
    """Check if input string represents a hex number."""
    try:
        int(input_str, 16)
    except ValueError:
        return False
    return True


def has_hex_prefix(input_str: str) -> bool:
    """Check if string value has hexa prefix.

    @param input_str: String value.
    @return: True is string value has hexa prefix.
    """
    return input_str.lower().startswith('0x')


def add_hex_prefix(input_str: str):  # type: ignore
    """Add 0x prefix to input string."""
    if has_hex_prefix(input_str):
        return input_str
    return '0x' + input_str


def to_int(input_str: str):  # type: ignore
    """Convert input string to int (JSON does not handle hex-formatted numbers...)."""
    try:
        # If conversion of int in base 10 fails, it's most likely a hex-formatted number
        int_val = int(input_str)
    except ValueError:
        try:
            int_val = int(input_str, 16)
        except Exception:
            raise Exception(f"{input_str} is not a number")
    return int_val


def str_to_int(string_val: str, base: int, default_val: int) -> int:
    """Convert string value to int.

    @param string_val: input value as string
    @param base: base of input value
    @param default_val: default value
    """
    try:
        integer_val = int(string_val, base)
    except ValueError:
        # Badly formatted log
        integer_val = default_val
    return integer_val
